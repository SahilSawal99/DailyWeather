package com.example.dailyweather.dto;

public class WindInfo {
    private double speed;
    private int deg;

    public WindInfo() {
    }

    public double getSpeed() {
        return speed;
    }

    public void setSpeed(double speed) {
        this.speed = speed;
    }

    public int getDeg() {
        return deg;
    }

    public void setDeg(int deg) {
        this.deg = deg;
    }
}

